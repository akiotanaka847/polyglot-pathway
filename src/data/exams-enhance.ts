function hasType(exam: Exam, type: string): boolean {
  return exam.sections.some(s => s.qs.some(q => q.t === type));
}

/**
 * Enhance an exam by adding listening, speaking, and writing sections if missing.
 * Picks questions based on difficulty level inferred from time budgets.
 */
export function enhanceExam(lang: string, exam: Exam): Exam {
  const bank = BANKS[lang];
  if (!bank) return exam;
  const names = SECTION_NAMES[lang] || SECTION_NAMES.es;

  const sections = [...exam.sections];

  // Determine how many questions to add based on exam complexity
  const totalExisting = sections.reduce((a, s) => a + s.qs.length, 0);
  const qCount = totalExisting >= 40 ? 10 : totalExisting >= 25 ? 8 : 6;

  // Add Listening section if no 'la' questions exist
  if (!hasType(exam, 'la')) {
    const listenQs: ListenAnswerStep[] = bank.listen.slice(0, qCount).map(l => ({
      t: 'la' as const,
      audio: l.audio,
      ans: l.ans,
      hint: l.hint,
    }));
    sections.push({
      name: names.listen,
      time: Math.max(10, Math.ceil(qCount * 1.5)),
      qs: listenQs,
    });
  }

  // Add Writing section if few 'tx' questions exist
  const existingTx = sections.reduce((a, s) => a + s.qs.filter(q => q.t === 'tx').length, 0);
  if (existingTx < 4) {
    const writeQs: TextStep[] = bank.write.slice(0, qCount).map(w => ({
      t: 'tx' as const,
      q: w.q,
      ans: w.ans,
      hint: w.hint,
    }));
    sections.push({
      name: names.write,
      time: Math.max(10, Math.ceil(qCount * 1.2)),
      qs: writeQs,
    });
  }

  // Add Speaking section if no/few 'sp' questions exist
  const existingSp = sections.reduce((a, s) => a + s.qs.filter(q => q.t === 'sp').length, 0);
  if (existingSp < 4) {
    const speakQs: SpeakStep[] = bank.speak.slice(0, qCount).map(s => ({
      t: 'sp' as const,
      q: s.q,
      expected: s.expected,
      hint: s.hint,
    }));
    sections.push({
      name: names.speak,
      time: Math.max(10, Math.ceil(qCount * 1.5)),
      qs: speakQs,
    });
  }

  return { ...exam, sections };
}
